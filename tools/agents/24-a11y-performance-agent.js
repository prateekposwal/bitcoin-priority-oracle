#!/usr/bin/env node
// BSAHI — 24 A11y & Performance Agent
// Audits contrast, reduced-motion support, aria, focus, and canvas loop hygiene
// in the public pages/JS. Writes reports/a11y/audit-<date>.md.
var path = require('path');
var fs = require('fs');

var REPO = path.resolve(__dirname, '..', '..');
var OUT = path.join(REPO, 'reports', 'a11y', 'audit-' + new Date().toISOString().slice(0, 10) + '.md');
var TARGETS = ['index.html', 'live.html', 'learn.html', 'capacity.html', 'fork-tracker.html', 'tools/viz-core.js', 'tools/viz-developer.js', 'tools/data-engine.js'];

function run() {
  var issues = [];
  var checks = [];

  TARGETS.forEach(function(f) {
    var p = path.join(REPO, f);
    if (!fs.existsSync(p)) return;
    var src = fs.readFileSync(p, 'utf8');
    var check = { file: f };

    // prefers-reduced-motion support
    check.reducedMotion = /prefers-reduced-motion/.test(src) ? 'ok' : 'NO prefers-reduced-motion';
    if (check.reducedMotion !== 'ok') issues.push(f + ': ' + check.reducedMotion);

    // onclick divs (non-keyboard-accessible)
    var onclickDivs = (src.match(/<div[^>]*onclick=/g) || []).length;
    check.onclickDivs = onclickDivs ? onclickDivs + ' onclick <div>s' : 'ok';
    if (onclickDivs) issues.push(f + ': ' + onclickDivs + ' non-keyboard <div onclick>');

    // low-contrast ticker text rgba(...,0.3) on dark bg
    var lowContrast = (src.match(/rgba\(255,255,255,0\.3\)/g) || []).length;
    check.lowContrast = lowContrast ? lowContrast + ' low-contrast' : 'ok';
    if (lowContrast) issues.push(f + ': ' + lowContrast + ' low-contrast rgba(255,255,255,0.3) text');

    checks.push(check);
  });

  // Canvas loop hygiene: setInterval without pause on hidden
  ['tools/viz-core.js'].forEach(function(f) {
    var p = path.join(REPO, f);
    if (!fs.existsSync(p)) return;
    var src = fs.readFileSync(p, 'utf8');
    if (!/visibilitychange/.test(src)) issues.push(f + ': no visibilitychange pause (canvas loops run on hidden tabs)');
  });

  var lines = ['# A11y & Performance Audit — ' + new Date().toISOString().slice(0, 10), ''];
  lines.push('## Result: ' + (issues.length ? 'ISSUES (' + issues.length + ')' : 'CLEAN'));
  lines.push('');
  if (issues.length) { lines.push('### Issues'); issues.forEach(function(i) { lines.push('- ' + i); }); }
  lines.push('### Checks');
  checks.forEach(function(c) {
    lines.push('- ' + c.file + ': reducedMotion=' + c.reducedMotion + ' onclickDivs=' + c.onclickDivs + ' contrast=' + c.lowContrast);
  });
  lines.push('_Generated by 24-a11y-performance-agent._');
  try {
    fs.mkdirSync(path.dirname(OUT), { recursive: true });
    fs.writeFileSync(OUT, lines.join('\n'));
  } catch (e) {}

  if (require.main === module) {
    console.log(lines.join('\n'));
    process.exit(issues.length ? 1 : 0);
  }
  return { issues: issues, checks: checks, out: OUT };
}

if (require.main === module) { run(); }
module.exports = { run: run };

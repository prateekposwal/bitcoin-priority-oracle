#!/usr/bin/env node
// BSAHI — 23 SEO Agent
// Generates + validates sitemap.xml, robots.txt, and meta consistency of the
// public pages. Writes reports/seo/audit-<date>.md.
var path = require('path');
var fs = require('fs');

var REPO = path.resolve(__dirname, '..', '..');
var PAGES = ['index.html', 'live.html', 'learn.html', 'capacity.html', 'fork-tracker.html', 'team.html'];
var ROUTES = ['/', '/live', '/capacity', '/learn', '/fork-tracker', '/team.html', '/feed.xml', '/api/v1/', '/data/snapshot.json'];
var OUT = path.join(REPO, 'reports', 'seo', 'audit-' + new Date().toISOString().slice(0, 10) + '.md');

function run() {
  var issues = [];
  var checks = [];

  PAGES.forEach(function(f) {
    var p = path.join(REPO, f);
    if (!fs.existsSync(p)) { issues.push(f + ': MISSING'); return; }
    var src = fs.readFileSync(p, 'utf8');
    var check = { page: f };
    check.lang = /<html lang="en">/.test(src) ? 'ok' : 'MISSING lang="en"';
    check.description = /<meta name="description"/.test(src) ? 'ok' : 'MISSING description';
    check.og = /property="og:title"/.test(src) ? 'ok' : 'MISSING og:title';
    check.canonical = /rel="canonical"/.test(src) ? 'ok' : 'MISSING canonical';
    if (check.lang !== 'ok') issues.push(f + ': ' + check.lang);
    if (check.description !== 'ok') issues.push(f + ': ' + check.description);
    if (check.og !== 'ok') issues.push(f + ': ' + check.og);
    if (check.canonical !== 'ok') issues.push(f + ': ' + check.canonical);
    checks.push(check);
  });

  // sitemap + robots presence
  var sitemap = path.join(REPO, 'sitemap.xml');
  var robots = path.join(REPO, 'robots.txt');
  if (!fs.existsSync(sitemap)) issues.push('sitemap.xml MISSING');
  if (!fs.existsSync(robots)) issues.push('robots.txt MISSING');

  var lines = ['# SEO Audit — ' + new Date().toISOString().slice(0, 10), ''];
  lines.push('## Result: ' + (issues.length ? 'ISSUES (' + issues.length + ')' : 'CLEAN'));
  lines.push('');
  if (issues.length) { lines.push('### Issues'); issues.forEach(function(i) { lines.push('- ' + i); }); }
  lines.push('### Page checks');
  checks.forEach(function(c) {
    lines.push('- ' + c.page + ': lang=' + c.lang + ' desc=' + c.description + ' og=' + c.og + ' canon=' + c.canonical);
  });
  lines.push('_Generated by 23-seo-agent._');
  try {
    fs.mkdirSync(path.dirname(OUT), { recursive: true });
    fs.writeFileSync(OUT, lines.join('\n'));
  } catch (e) {}

  if (require.main === module) {
    console.log(lines.join('\n'));
    process.exit(issues.length ? 1 : 0);
  }
  return { issues: issues, checks: checks, out: OUT };
}

if (require.main === module) { run(); }
module.exports = { run: run, ROUTES: ROUTES };

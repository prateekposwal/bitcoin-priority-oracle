#!/usr/bin/env node
// BSAHI — 23 SEO Agent
// Generates + validates sitemap.xml, robots.txt, and meta consistency of the
// public pages. Writes reports/seo/audit-<date>.md.
var path = require('path');
var fs = require('fs');

var REPO = path.resolve(__dirname, '..', '..');
var PAGES = ['index.html', 'live.html', 'learn.html', 'capacity.html', 'fork-tracker.html'];
var ROUTES = ['/', '/live', '/capacity', '/learn', '/fork-tracker', '/feed.xml', '/api/v1/', '/data/snapshot.json'];
var OUT = path.join(REPO, 'reports', 'seo', 'audit-' + new Date().toISOString().slice(0, 10) + '.md');

function checkPage(src, fileName) {
  var check = { page: fileName };
  check.lang = /<html lang="en">/.test(src) ? 'ok' : 'MISSING lang="en"';
  var mTitle = src.match(/<title>([^<]*)<\/title>/);
  check.title = (mTitle && mTitle[1].trim().length >= 10) ? 'ok' : 'MISSING/short title';
  check.viewport = /name="viewport"/.test(src) ? 'ok' : 'MISSING viewport';
  var mDesc = src.match(/<meta name="description" content="([^"]*)"/);
  check.descLen = (mDesc && mDesc[1].length >= 140 && mDesc[1].length <= 165) ? 'ok (' + (mDesc ? mDesc[1].length : 0) + 'ch)' : 'desc ' + (mDesc ? mDesc[1].length : 0) + 'ch (want 140-165)';
  check.og = /property="og:title"/.test(src) ? 'ok' : 'MISSING og:title';
  check.ogImage = /property="og:image"/.test(src) ? 'ok' : 'MISSING og:image';
  check.canonical = /rel="canonical"/.test(src) ? 'ok' : 'MISSING canonical';
  check.jsonld = /application\/ld\+json/.test(src) ? 'ok' : 'MISSING JSON-LD';
  var h1s = (src.match(/<h1[\s>]/g) || []).length;
  check.h1 = h1s === 1 ? 'ok' : (h1s === 0 ? 'MISSING H1' : h1s + ' H1s (want exactly 1)');
  return check;
}

function checkIssue(check, field, issues) {
  var v = check[field];
  if (v !== 'ok' && v.indexOf('ok (') !== 0) issues.push(check.page + ': ' + v);
}

function run() {
  var issues = [];
  var checks = [];

  PAGES.forEach(function(f) {
    var p = path.join(REPO, f);
    if (!fs.existsSync(p)) { issues.push(f + ': MISSING'); return; }
    var src = fs.readFileSync(p, 'utf8');
    var check = checkPage(src, f);
    if (f === 'embed.html') {
      check.robots = /name="robots"[^>]*noindex/.test(src) ? 'ok' : 'MISSING robots noindex';
      checkIssue(check, 'robots', issues);
    }
    ['lang', 'title', 'viewport', 'descLen', 'og', 'ogImage', 'canonical', 'jsonld', 'h1'].forEach(function(field) {
      checkIssue(check, field, issues);
    });
    checks.push(check);
  });

  // embed.html special-case (widget, must be noindex)
  var embedPath = path.join(REPO, 'embed.html');
  if (fs.existsSync(embedPath)) {
    var esrc = fs.readFileSync(embedPath, 'utf8');
    if (!/name="robots"[^>]*noindex/.test(esrc)) issues.push('embed.html: MISSING robots noindex');
  }

  // Research pages sweep (if generated)
  var researchDir = path.join(REPO, 'research');
  if (fs.existsSync(researchDir)) {
    fs.readdirSync(researchDir).filter(function(f) { return f.endsWith('.html'); }).forEach(function(f) {
      var src = fs.readFileSync(path.join(researchDir, f), 'utf8');
      var check = checkPage(src, 'research/' + f);
      ['title', 'descLen', 'h1', 'canonical', 'jsonld'].forEach(function(field) { checkIssue(check, field, issues); });
      checks.push(check);
    });
  }

  // sitemap + robots presence
  var sitemap = path.join(REPO, 'sitemap.xml');
  var robots = path.join(REPO, 'robots.txt');
  if (!fs.existsSync(sitemap)) issues.push('sitemap.xml MISSING');
  if (!fs.existsSync(robots)) issues.push('robots.txt MISSING');

  var lines = ['# SEO Audit — ' + new Date().toISOString().slice(0, 10), ''];
  lines.push('## Result: ' + (issues.length ? 'ISSUES (' + issues.length + ')' : 'CLEAN'));
  lines.push('');
  if (issues.length) { lines.push('### Issues'); issues.forEach(function(i) { lines.push('- ' + i); }); }
  lines.push('### Page checks');
  checks.forEach(function(c) {
    lines.push('- ' + c.page + ': lang=' + c.lang + ' title=' + c.title + ' viewport=' + c.viewport + ' desc=' + c.descLen + ' og=' + c.og + ' ogimg=' + c.ogImage + ' canon=' + c.canonical + ' ld=' + c.jsonld + ' h1=' + c.h1);
  });
  lines.push('_Generated by 23-seo-agent._');
  try {
    fs.mkdirSync(path.dirname(OUT), { recursive: true });
    fs.writeFileSync(OUT, lines.join('\n'));
  } catch (e) {}

  if (require.main === module) {
    console.log(lines.join('\n'));
    process.exit(issues.length ? 1 : 0);
  }
  return { issues: issues, checks: checks, out: OUT };
}

if (require.main === module) { run(); }
module.exports = { run: run, ROUTES: ROUTES, checkPage: checkPage };

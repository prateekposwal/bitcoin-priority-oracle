#!/usr/bin/env node
// BSAHI — 17 Report Generator
// Generates daily/weekly research reports from spool-derived data + SQLite
// (never root flat files). Complements report.js (DE infra report).
var path = require('path');
var fs = require('fs');

var REPO = path.resolve(__dirname, '..', '..');
var OUT_DIR = path.join(REPO, 'reports', 'research');
var STATE_FILE = path.join(REPO, 'captured-data', 'report-agent-state.json');

function loadJson(p, fb) { try { return JSON.parse(fs.readFileSync(p, 'utf8')); } catch (e) { return fb; } }

function run() {
  var today = new Date().toISOString().slice(0, 10);
  var lines = [];
  lines.push('# BSAHI Research Report — ' + today);
  lines.push('');

  return require('../data-engineering/spool.js').init().then(function(spool) { return spool.stats(); }).then(function(st) {
    var db = require('../db/init.js');

    var todayCount = 0;
    try {
      var r = db.query("SELECT COUNT(*) AS c FROM captures WHERE date(captured_at) = date('now')");
      todayCount = r && r[0] ? r[0].c : 0;
    } catch (e) {}

    var bySource = [];
    try {
      var rows = db.query("SELECT source, COUNT(*) AS c FROM captures GROUP BY source ORDER BY c DESC LIMIT 15");
      if (Array.isArray(rows)) bySource = rows;
    } catch (e) {}

    var forecast = loadJson(path.join(REPO, 'tools', 'fee_forecast.json'), null);
    var signal = loadJson(path.join(REPO, 'captured-data', 'topic-signal.json'), null);

    lines.push('## Data');
    lines.push('- Spool lifetime: ' + (st.history ? st.history.totalEnqueued : st.totals.enqueued) + ' entries (' + todayCount + ' today)');
    lines.push('- Captures in SQLite by source:');
    bySource.forEach(function(r2) { lines.push('  - ' + r2.source + ': ' + r2.c + ' rows'); });
    lines.push('');

    lines.push('## Fee Forecast');
    if (forecast && forecast.data_points > 0) {
      lines.push('- Trend: ' + forecast.trend + ' (slope ' + forecast.slope + '), ' + forecast.data_points + ' points');
      (forecast.forecast || []).forEach(function(f) {
        lines.push('  - +' + f.day_offset + 'd: ~' + f.predicted_fastest_fee + ' sat/vB (' + f.trend + ')');
      });
    } else {
      lines.push('- No forecast data yet');
    }
    lines.push('');

    lines.push('## Audience Signal');
    if (signal && signal.weights) {
      var top = Object.keys(signal.weights).sort(function(a, b) { return signal.weights[b] - signal.weights[a]; }).slice(0, 5);
      top.forEach(function(t) { lines.push('- ' + t + ': ' + signal.weights[t].toFixed(2)); });
    }
    lines.push('');
    lines.push('_Generated by 17-report-generator from spool + SQLite._');

    if (!fs.existsSync(OUT_DIR)) fs.mkdirSync(OUT_DIR, { recursive: true });
    var file = path.join(OUT_DIR, today + '.md');
    fs.writeFileSync(file, lines.join('\n'));
    fs.writeFileSync(STATE_FILE, JSON.stringify({ lastRun: new Date().toISOString(), report: file }, null, 2));
    if (require.main === module) console.log('report-generator: wrote ' + file);
    return { file: file, today: todayCount };
  });
}

if (require.main === module) {
  run().then(function() { process.exit(0); }).catch(function(e) { console.error(e); process.exit(1); });
}

module.exports = { run: run };
